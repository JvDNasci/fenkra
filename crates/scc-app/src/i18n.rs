//! Português / inglês. A interface é escrita em português; `tr` devolve a tradução quando o
//! inglês está ativo (Configurações → Interface → Idioma). Textos sem tradução ficam em português.

use std::collections::HashMap;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::OnceLock;

static EN: AtomicBool = AtomicBool::new(false);

pub fn set_english(on: bool) {
    EN.store(on, Ordering::Relaxed);
}

pub fn english() -> bool {
    EN.load(Ordering::Relaxed)
}

fn map() -> &'static HashMap<&'static str, &'static str> {
    static M: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    M.get_or_init(|| TABLE.iter().copied().collect())
}

/// Tradução do texto (ou o próprio texto, em português ou sem tradução).
pub fn tr(s: &str) -> &str {
    if english() {
        if let Some(e) = map().get(s) {
            return e;
        }
    }
    s
}

